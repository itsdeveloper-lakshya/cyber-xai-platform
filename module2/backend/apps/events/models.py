import uuid
from django.db import models
from devices.models import ExtDevice

class ExtPasteEvent(models.Model):
    """
    ext_paste_event (Section 5.1)
    Stores paste & file upload metadata evaluated client-side.
    Data minimization principle: Never stores raw text or file content.
    """
    event_id = models.UUIDField(primary_key=True, default=uuid.uuid4, help_text="Generated by extension for idempotency")
    device = models.ForeignKey(ExtDevice, on_delete=models.CASCADE, null=True, blank=True, db_column="device_id")
    user_id = models.CharField(max_length=32)
    occurred_at = models.DateTimeField(help_text="Client timestamp")
    received_at = models.DateTimeField(auto_now_add=True, help_text="Server timestamp")
    site_domain = models.CharField(max_length=100)
    event_type = models.CharField(max_length=12, help_text="paste or upload")
    content_length = models.IntegerField(help_text="Characters (paste) or bytes (upload)")
    line_count = models.IntegerField(default=0)
    file_extension = models.CharField(max_length=16, null=True, blank=True)
    matched_categories = models.JSONField(default=list, help_text="Rule categories that fired, no text")
    regex_score = models.FloatField(default=0.0)
    ml_score = models.FloatField(default=0.0)
    final_score = models.FloatField(default=0.0)
    risk_tier = models.CharField(max_length=8, help_text="low, medium, high")
    action = models.CharField(max_length=8, help_text="logged, warned, blocked")
    override_used = models.BooleanField(default=False)
    override_reason = models.TextField(null=True, blank=True)
    content_hash = models.CharField(max_length=64, null=True, blank=True)
    ruleset_version = models.IntegerField(default=1)
    model_version = models.IntegerField(default=1)

    class Meta:
        db_table = "ext_paste_event"
        indexes = [
            models.Index(fields=["user_id", "occurred_at"]),
            models.Index(fields=["occurred_at"]),
            models.Index(fields=["risk_tier", "occurred_at"]),
        ]

    def __str__(self):
        return f"Event {self.event_id} ({self.site_domain} - {self.risk_tier})"

class ExtDailyPasteAgg(models.Model):
    """
    ext_daily_paste_agg (Section 5.1 & B5)
    Daily aggregated paste & upload metrics per employee.
    """
    user_id = models.CharField(max_length=32)
    date = models.DateField()
    paste_count = models.IntegerField(default=0)
    upload_count = models.IntegerField(default=0)
    medium_count = models.IntegerField(default=0)
    high_count = models.IntegerField(default=0)
    blocked_count = models.IntegerField(default=0)
    override_count = models.IntegerField(default=0)

    class Meta:
        db_table = "ext_daily_paste_agg"
        unique_together = ("user_id", "date")

    def __str__(self):
        return f"{self.user_id} on {self.date} (High: {self.high_count})"
